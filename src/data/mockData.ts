export interface DistrictData {
  name: string;
  state: string;
  population: number;
  agricultureArea: number;
  forestCover: number;
  literacyRate: number;
  landDisputes: number;
  irrigationCoverage: number;
  ruralHouseholds: number;
  researchPapers: number;
  povertyRate: number;
  connectivity: number;
}

export function getDistrictData(district: string, state: string): DistrictData {
  const seed = (district.charCodeAt(0) + state.charCodeAt(0)) % 100;
  return {
    name: district,
    state,
    population: 800000 + seed * 12000,
    agricultureArea: 45 + (seed % 35),
    forestCover: 12 + (seed % 28),
    literacyRate: 62 + (seed % 25),
    landDisputes: 120 + seed * 8,
    irrigationCoverage: 38 + (seed % 42),
    ruralHouseholds: 65 + (seed % 20),
    researchPapers: 8 + (seed % 15),
    povertyRate: 18 + (seed % 22),
    connectivity: 72 + (seed % 18),
  };
}

